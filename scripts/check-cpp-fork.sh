#!/usr/bin/env bash
# Checks the Apache Arrow C++ fork in cpp/arrow (cpp/arrow/FORK.md): downloads the Arrow source
# release (cached in target/cpp/dl), verifies its sha512, checks that FORK.md records it, that
# cpp/arrow/FORK.patch applies cleanly, that it only touches the files FORK.md lists, and, when
# the thrift compiler is installed, that its change to the checked-in generated thrift code is
# exactly what the compiler generates for its change to parquet.thrift.
#
#   scripts/check-cpp-fork.sh                 check
#   scripts/check-cpp-fork.sh --update [SRC]  rewrite cpp/arrow/FORK.patch from the edited
#                                             tree SRC (default target/cpp/arrow-src)
set -euo pipefail

version=26.0.1
sha512=2ee7efc6ae5b1a2d2c4f2daa52110d16d2e64c02f27f341b462459341528bdcdc796c043c4834baa80dbcb4bac0219d1c705741485973e9207656124f83e74dd
url="https://dlcdn.apache.org/arrow/arrow-${version}/apache-arrow-${version}.tar.gz"

root=$(cd "$(dirname "$0")/.." && pwd)
fork="$root/cpp/arrow"
dl="$root/target/cpp/dl"
tarball="$dl/apache-arrow-${version}.tar.gz"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

grep -q "$sha512" "$fork/FORK.md" || { echo "check-cpp-fork: FORK.md does not record sha512 $sha512" >&2; exit 1; }
grep -q "apache-arrow-${version}.tar.gz" "$fork/FORK.md" || { echo "check-cpp-fork: FORK.md does not name apache-arrow-${version}" >&2; exit 1; }
grep -q "$sha512" "$fork/prepare.sh" || { echo "check-cpp-fork: prepare.sh does not verify sha512 $sha512" >&2; exit 1; }

verified() { echo "$sha512  $tarball" | sha512sum --check --quiet --status - 2>/dev/null; }
if ! verified; then
    mkdir -p "$dl"
    curl -sSfL --retry 3 -o "$tarball.part" "$url"
    mv "$tarball.part" "$tarball"
    verified || { echo "check-cpp-fork: sha512 mismatch for $url" >&2; rm -f "$tarball"; exit 1; }
fi
mkdir "$work/upstream"
tar -xzf "$tarball" -C "$work/upstream" --strip-components=1 apache-arrow-${version}/cpp

if [ "${1:-}" = "--update" ]; then
    src=${2:-$root/target/cpp/arrow-src}
    mkdir "$work/fork"
    cp -a "$src/cpp" "$work/fork/cpp"
    cd "$work"
    status=0
    git -c core.quotepath=off diff --no-index --no-color --no-ext-diff --no-renames --full-index \
        --diff-algorithm=myers --no-prefix upstream fork > fork.diff || status=$?
    [ "$status" -le 1 ] || { echo "check-cpp-fork: git diff failed" >&2; exit "$status"; }
    cp fork.diff "$fork/FORK.patch"
    sha256sum "$fork/FORK.patch" | cut -d' ' -f1 > "$src/.tparquet-fork"
    echo "check-cpp-fork: wrote cpp/arrow/FORK.patch ($(grep -c '^diff --git' fork.diff) files, $(wc -l < fork.diff) lines)"
    exit 0
fi

cd "$work/upstream"
patch -p1 --batch --forward --dry-run --quiet < "$fork/FORK.patch" || { echo "check-cpp-fork: FORK.patch does not apply cleanly to Arrow ${version}" >&2; exit 1; }

# every file the patch touches is listed in FORK.md's table, and every listed file is patched
files=$(sed -n 's|^diff --git [^ ]* fork/\(.*\)$|\1|p' "$fork/FORK.patch" | sort -u)
listed=$(sed -n 's/^| `\(cpp\/[^`]*\)` |.*/\1/p' "$fork/FORK.md" | sort -u)
if [ "$files" != "$listed" ]; then
    echo "check-cpp-fork: the files FORK.patch changes differ from FORK.md's table:" >&2
    diff <(echo "$files") <(echo "$listed") >&2 || true
    exit 1
fi

cp -a "$work/upstream" "$work/patched"
(cd "$work/patched" && patch -p1 --batch --forward --quiet < "$fork/FORK.patch")

if command -v thrift > /dev/null; then
    mkdir "$work/gen-upstream" "$work/gen-patched"
    thrift --gen cpp:moveable_types,templates -out "$work/gen-upstream" "$work/upstream/cpp/src/parquet/parquet.thrift"
    thrift --gen cpp:moveable_types,templates -out "$work/gen-patched" "$work/patched/cpp/src/parquet/parquet.thrift"
    for f in parquet_types.h parquet_types.cpp parquet_types.tcc; do
        # the generator's change, without file names and hunk positions...
        diff "$work/gen-upstream/$f" "$work/gen-patched/$f" | grep '^[<>]' > "$work/want" || true
        # ...equals the fork's change to the checked-in code (generated by a newer thrift)
        diff "$work/upstream/cpp/src/generated/$f" "$work/patched/cpp/src/generated/$f" | grep '^[<>]' > "$work/got" || true
        if ! cmp -s "$work/want" "$work/got"; then
            echo "check-cpp-fork: cpp/src/generated/$f is not what thrift $(thrift --version) generates for the patched parquet.thrift:" >&2
            diff "$work/want" "$work/got" >&2 || true
            exit 1
        fi
    done
    thrift_note=", generated thrift code checked"
else
    thrift_note=", generated thrift code not checked (no thrift compiler)"
fi
echo "check-cpp-fork: FORK.patch applies to Arrow ${version} (sha512 ${sha512:0:16}...), $(echo "$files" | wc -l) files as listed in FORK.md${thrift_note}"
